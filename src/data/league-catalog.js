const BY_SLUG = new Map(LEAGUE_CATALOG.map((entry) => [entry.slug, entry]));

/** Look up a catalog entry by exact slug; returns null for unknown slugs. */
export function findLeagueCatalogEntry(slug) {
  return typeof slug === "string" ? (BY_SLUG.get(slug) ?? null) : null;
}

/** Region names in display order: Popular, countries A–Z, International last. */
export function leagueCatalogRegions() {
  const seen = [];
  const known = new Set();
  for (const entry of LEAGUE_CATALOG) {
    if (!known.has(entry.region)) {
      known.add(entry.region);
      seen.push(entry.region);
    }
  }
  return Object.freeze(seen);
}
